/* Carrousel scientifique — logique côté navigateur (sans dépendance). */
(() => {
  "use strict";

  const AUTOPLAY_MS = 12000;
  const reducedMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const state = {
    articles: [],
    topics: [],
    filter: null,
    index: 0,
    playing: !reducedMotion,
    paused: false,
    progressStart: 0,
    status: null,
    clockOffset: 0,
    newIds: new Set(),
  };

  const $ = (id) => document.getElementById(id);
  const els = {
    track: $("track"), viewport: $("viewport"), dots: $("dots"), counter: $("counter"),
    prev: $("prev"), next: $("next"), play: $("play"), progress: $("progress").firstElementChild,
    filters: $("filters"), empty: $("empty"), reader: $("reader"), readerContent: $("reader-content"),
    readerClose: $("reader-close"), toast: $("toast"), statusCount: $("status-count"), statusNext: $("status-next"),
    carousel: $("carousel"),
  };

  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  /* ---------- Textes de l'interface (la langue vient de /api/status, défaut : fr) ---------- */
  const STRINGS = {
    fr: {
      title: "Carrousel scientifique",
      subtitle: "Pharma · peptides · nouveaux médicaments · biosimilaires — à partir de PubMed / NCBI",
      footer: "Contenus générés automatiquement à partir des résumés PubMed ; ils ne constituent pas un avis médical. Sources citées sur chaque fiche.",
      read: "Lire l'article", source: "Source sur PubMed", published: "Publié le", generated: "Généré le",
      next: "Prochain article dans", now: "génération en cours…", articles: (n) => `${n} article${n > 1 ? "s" : ""}`,
      newArticle: "Nouvel article", keyPoints: "Points clés", authors: "Auteurs", journal: "Revue", pmid: "PMID", doi: "DOI",
      pubTypes: "Types de publication", disclaimer: "Article généré automatiquement à partir du résumé PubMed (résumé seul, pas le texte intégral). Il ne constitue pas un avis médical.",
      generatedBy: "Généré par", image: "Illustration", autoplay: "Défilement automatique", of: "sur", all: "Tous",
      prev: "Article précédent", nextBtn: "Article suivant", close: "Fermer", slide: "diapositive", chooseArticle: "Choisir un article",
      emptyAll: "Aucun article pour le moment : le premier sera généré dans quelques instants.",
      emptyFilter: "Aucun article pour ce sujet pour le moment.", loadError: "Impossible de charger les articles.",
      articleN: (n) => `Article ${n}`,
    },
    en: {
      title: "Science carousel",
      subtitle: "Pharma · peptides · new drugs · biosimilars — from PubMed / NCBI",
      footer: "Content generated automatically from PubMed abstracts; it is not medical advice. Sources are cited on every card.",
      read: "Read the article", source: "Source on PubMed", published: "Published", generated: "Generated",
      next: "Next article in", now: "generating…", articles: (n) => `${n} article${n > 1 ? "s" : ""}`,
      newArticle: "New article", keyPoints: "Key points", authors: "Authors", journal: "Journal", pmid: "PMID", doi: "DOI",
      pubTypes: "Publication types", disclaimer: "Article generated automatically from the PubMed abstract (abstract only, not the full text). It is not medical advice.",
      generatedBy: "Generated by", image: "Illustration", autoplay: "Autoplay", of: "of", all: "All",
      prev: "Previous article", nextBtn: "Next article", close: "Close", slide: "slide", chooseArticle: "Choose an article",
      emptyAll: "No article yet: the first one will be generated shortly.",
      emptyFilter: "No article for this topic yet.", loadError: "Unable to load articles.",
      articleN: (n) => `Article ${n}`,
    },
  };
  let lang = "fr";
  let T = STRINGS.fr;
  let dateFmt;
  let timeFmt;

  function setLang(next) {
    lang = STRINGS[next] ? next : "fr";
    T = STRINGS[lang];
    document.documentElement.lang = lang;
    const locale = lang === "en" ? "en-GB" : "fr-FR";
    dateFmt = new Intl.DateTimeFormat(locale, { dateStyle: "medium" });
    timeFmt = new Intl.DateTimeFormat(locale, { hour: "2-digit", minute: "2-digit" });
    document.title = `${T.title} — ${T.subtitle.split(" — ")[0]}`;
    for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = T[el.dataset.i18n] ?? el.textContent;
    els.prev.setAttribute("aria-label", T.prev);
    els.next.setAttribute("aria-label", T.nextBtn);
    els.readerClose.setAttribute("aria-label", T.close);
    els.play.setAttribute("aria-label", T.autoplay);
    els.dots.setAttribute("aria-label", T.chooseArticle);
    els.carousel.setAttribute("aria-roledescription", lang === "en" ? "carousel" : "carrousel");
  }
  setLang("fr");

  function formatDate(value) {
    if (!value) return "";
    if (/^\d{4}-\d{2}-\d{2}/.test(value)) {
      const d = new Date(value.length === 10 ? `${value}T12:00:00` : value);
      return Number.isNaN(d.getTime()) ? value : dateFmt.format(d);
    }
    return value;
  }

  const safeHttpUrl = (u) => (/^https?:\/\//i.test(String(u ?? "")) ? String(u) : "");

  function visible() {
    return state.filter ? state.articles.filter((a) => a.topic && a.topic.id === state.filter) : state.articles;
  }

  function hueOf(article) {
    return article.topic && typeof article.topic.hue === "number" ? article.topic.hue : 190;
  }

  /* Les styles en ligne sont interdits par la CSP : la couleur du sujet est posée via CSSOM. */
  function applyHues(root) {
    for (const el of root.querySelectorAll("[data-hue]")) {
      el.style.setProperty("--chip", `hsl(${Number(el.dataset.hue)} 85% 65%)`);
    }
  }

  function slideHtml(article, i, total) {
    const src = article.source || {};
    const isNew = state.newIds.has(article.id);
    const sourceUrl = safeHttpUrl(src.url);
    return `
      <li class="slide" data-id="${esc(article.id)}" role="group" aria-roledescription="${T.slide}" aria-label="${i + 1} ${T.of} ${total}" data-hue="${hueOf(article)}">
        <div class="slide-media">
          ${article.image ? `<img src="${esc(article.image.url)}" alt="${esc(article.image.alt || "")}" ${i === 0 ? "" : 'loading="lazy"'} width="1200" height="675" draggable="false">` : ""}
          <span class="badge">${esc(article.topic ? article.topic.label : "")}</span>
          ${isNew ? `<span class="badge new">${esc(T.newArticle)}</span>` : ""}
        </div>
        <div class="slide-body">
          <div class="meta">
            <span class="journal">${esc(src.journal || src.journalAbbrev || "PubMed")}</span>
            ${src.pubDate ? `<span>${esc(T.published)} ${esc(formatDate(src.pubDate))}</span>` : ""}
            <span>${esc(T.generated)} ${esc(formatDate(article.createdAt))} ${esc(timeFmt.format(new Date(article.createdAt)))}</span>
          </div>
          <h2>${esc(article.title)}</h2>
          <p class="dek">${esc(article.dek)}</p>
          <p class="summary">${esc(article.summary)}</p>
          ${article.keyPoints && article.keyPoints.length ? `<ul class="keypoints">${article.keyPoints.slice(0, 3).map((k) => `<li>${esc(k)}</li>`).join("")}</ul>` : ""}
          <div class="tags">${(article.tags || []).slice(0, 6).map((t) => `<span class="tag">${esc(t)}</span>`).join("")}</div>
          <div class="actions">
            <button class="btn" type="button" data-read="${esc(article.id)}">${esc(T.read)}</button>
            ${sourceUrl ? `<a class="link" href="${esc(sourceUrl)}" target="_blank" rel="noopener noreferrer">${esc(T.source)} ↗</a>` : ""}
          </div>
        </div>
      </li>`;
  }

  /* Décrit le contrôle du carrousel qui a le focus, pour le restaurer après un re-rendu. */
  function focusedControl() {
    const active = document.activeElement;
    if (!active || active === document.body) return null;
    if (els.track.contains(active)) {
      const slide = active.closest(".slide");
      if (!slide) return null;
      return { where: "slide", id: slide.dataset.id, selector: active.matches("[data-read]") ? "button[data-read]" : "a.link" };
    }
    if (els.dots.contains(active)) return { where: "dots", index: Number(active.dataset.goto) };
    return null;
  }

  function restoreFocus(ctl) {
    if (!ctl) return;
    let target = null;
    if (ctl.where === "slide") {
      const slide = [...els.track.children].find((li) => li.dataset.id === ctl.id);
      target = slide && slide.querySelector(ctl.selector);
    } else if (ctl.where === "dots") {
      target = els.dots.querySelector(`button[data-goto="${Math.min(ctl.index, els.dots.children.length - 1)}"]`);
    }
    if (target) target.focus({ preventScroll: true });
  }

  function render({ keepId } = {}) {
    const list = visible();
    const focus = focusedControl();
    els.empty.hidden = list.length > 0;
    els.empty.textContent = state.filter ? T.emptyFilter : T.emptyAll;
    els.carousel.style.visibility = list.length ? "visible" : "hidden";
    els.track.innerHTML = list.map((a, i) => slideHtml(a, i, list.length)).join("");
    applyHues(els.track);
    els.dots.innerHTML = list.map((a, i) => `<li><button type="button" data-goto="${i}" aria-label="${esc(T.articleN(i + 1))}: ${esc(a.title)}"></button></li>`).join("");
    if (keepId) {
      const idx = list.findIndex((a) => a.id === keepId);
      state.index = idx >= 0 ? idx : 0;
    }
    state.index = Math.min(state.index, Math.max(list.length - 1, 0));
    position({ animate: false });
    restoreFocus(focus);
  }

  function position({ animate = true } = {}) {
    const list = visible();
    els.track.classList.toggle("no-anim", !animate);
    els.track.style.transform = `translateX(-${state.index * 100}%)`;
    if (!animate) void els.track.offsetWidth; // force le reflow pour que la prochaine transition s'anime
    els.viewport.scrollLeft = 0; // un défilement de focus ne doit jamais s'ajouter à la translation
    [...els.track.children].forEach((slide, i) => {
      const hidden = i !== state.index;
      slide.inert = hidden; // les diapositives masquées ne sont ni focalisables ni lues
      slide.setAttribute("aria-hidden", String(hidden));
    });
    els.counter.textContent = list.length ? `${state.index + 1} / ${list.length}` : "";
    for (const btn of els.dots.querySelectorAll("button")) {
      btn.setAttribute("aria-current", Number(btn.dataset.goto) === state.index ? "true" : "false");
    }
    els.prev.disabled = list.length < 2;
    els.next.disabled = list.length < 2;
    restartProgress();
  }

  function goTo(i, opts) {
    const n = visible().length;
    if (!n) return;
    state.index = ((i % n) + n) % n;
    position(opts);
  }
  const next = () => goTo(state.index + 1);
  const prev = () => goTo(state.index - 1);

  /* ---------- Défilement automatique avec barre de progression ---------- */
  function restartProgress() {
    state.progressStart = performance.now();
    els.progress.style.width = "0%";
  }
  function loop(now) {
    if (state.playing && !state.paused && visible().length > 1) {
      const elapsed = now - state.progressStart;
      els.progress.style.width = `${Math.min(100, (elapsed / AUTOPLAY_MS) * 100)}%`;
      if (elapsed >= AUTOPLAY_MS) next();
    } else {
      state.progressStart = now - (parseFloat(els.progress.style.width) || 0) / 100 * AUTOPLAY_MS;
    }
    requestAnimationFrame(loop);
  }
  function setPlaying(playing) {
    state.playing = playing;
    els.play.setAttribute("aria-pressed", String(playing));
    els.play.textContent = playing ? "❚❚" : "▶";
    if (playing) restartProgress();
  }

  /* ---------- Lecteur d'article complet ---------- */
  function openReader(article) {
    if (els.reader.open) return;
    const src = article.source || {};
    const authors = (src.authors || []).slice(0, 10).join(", ") + ((src.authors || []).length > 10 ? " et al." : "");
    const sourceUrl = safeHttpUrl(src.url);
    const doiUrl = safeHttpUrl(src.doiUrl || (src.doi ? `https://doi.org/${src.doi}` : ""));
    els.readerContent.innerHTML = `
      <span class="badge badge-inline" data-hue="${hueOf(article)}">${esc(article.topic ? article.topic.label : "")}</span>
      <h2 id="reader-title">${esc(article.title)}</h2>
      <p class="dek">${esc(article.dek)}</p>
      ${article.image ? `<img src="${esc(article.image.url)}" alt="${esc(article.image.alt || "")}" width="1200" height="675">` : ""}
      <p><strong>${esc(article.summary)}</strong></p>
      ${(article.sections || []).map((s) => `<h3>${esc(s.heading)}</h3><p>${esc(s.content)}</p>`).join("")}
      ${article.keyPoints && article.keyPoints.length ? `<h3>${esc(T.keyPoints)}</h3><ul>${article.keyPoints.map((k) => `<li>${esc(k)}</li>`).join("")}</ul>` : ""}
      <div class="tags">${(article.tags || []).map((t) => `<span class="tag">${esc(t)}</span>`).join("")}</div>
      <div class="source">
        <div><strong>${esc(src.title || "")}</strong></div>
        ${authors ? `<div>${esc(T.authors)} : ${esc(authors)}</div>` : ""}
        <div>${esc(T.journal)} : ${esc(src.journal || "")}${src.pubDate ? ` · ${esc(T.published)} ${esc(formatDate(src.pubDate))}` : ""}</div>
        ${src.publicationTypes && src.publicationTypes.length ? `<div>${esc(T.pubTypes)} : ${esc(src.publicationTypes.join(", "))}</div>` : ""}
        <div>${esc(T.pmid)} : ${sourceUrl ? `<a href="${esc(sourceUrl)}" target="_blank" rel="noopener noreferrer">${esc(src.pmid)}</a>` : esc(src.pmid)}${src.doi ? ` · ${esc(T.doi)} : ${doiUrl ? `<a href="${esc(doiUrl)}" target="_blank" rel="noopener noreferrer">${esc(src.doi)}</a>` : esc(src.doi)}` : ""}</div>
        <p class="disclaimer">${esc(T.disclaimer)} ${esc(T.generatedBy)} ${esc(article.generator || "")} · ${esc(T.image)} : ${esc(article.image ? article.image.provider : "")}.</p>
      </div>`;
    applyHues(els.readerContent);
    state.paused = true;
    els.reader.showModal();
    els.readerContent.scrollTop = 0;
  }
  els.readerClose.addEventListener("click", () => els.reader.close());
  els.reader.addEventListener("close", () => { state.paused = false; restartProgress(); });
  els.reader.addEventListener("click", (e) => { if (e.target === els.reader) els.reader.close(); });

  /* ---------- Filtres par sujet ---------- */
  function renderFilters() {
    const all = `<button type="button" data-topic="" aria-pressed="${state.filter ? "false" : "true"}">${esc(T.all)}</button>`;
    els.filters.innerHTML = all + state.topics.map((t) =>
      `<button type="button" data-topic="${esc(t.id)}" aria-pressed="${state.filter === t.id ? "true" : "false"}" data-hue="${Number(t.hue) || 190}">${esc(t.label)}</button>`).join("");
    applyHues(els.filters);
  }
  els.filters.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-topic]");
    if (!btn) return;
    state.filter = btn.dataset.topic || null;
    state.index = 0;
    renderFilters();
    render();
  });

  /* ---------- Navigation ---------- */
  els.next.addEventListener("click", next);
  els.prev.addEventListener("click", prev);
  els.play.addEventListener("click", () => setPlaying(!state.playing));
  els.dots.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-goto]");
    if (btn) goTo(Number(btn.dataset.goto));
  });
  els.track.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-read]");
    if (!btn) return;
    const article = state.articles.find((a) => a.id === btn.dataset.read);
    if (article) openReader(article);
  });
  document.addEventListener("keydown", (e) => {
    if (els.reader.open) return;
    if (e.key === "ArrowRight") next();
    else if (e.key === "ArrowLeft") prev();
    else if (e.key === " " && e.target === document.body) { e.preventDefault(); setPlaying(!state.playing); }
  });
  els.carousel.addEventListener("mouseenter", () => { state.paused = true; });
  els.carousel.addEventListener("mouseleave", () => { if (!els.reader.open) state.paused = false; });
  els.carousel.addEventListener("focusin", () => { state.paused = true; });
  els.carousel.addEventListener("focusout", () => { if (!els.reader.open) state.paused = false; });
  document.addEventListener("visibilitychange", () => { state.paused = document.hidden || els.reader.open; });

  let pointerStart = null;
  els.viewport.addEventListener("pointerdown", (e) => {
    if (e.target.closest("button, a")) { pointerStart = null; return; }
    pointerStart = { x: e.clientX, y: e.clientY };
  });
  els.viewport.addEventListener("pointercancel", () => { pointerStart = null; });
  els.viewport.addEventListener("pointerup", (e) => {
    if (!pointerStart) return;
    const dx = e.clientX - pointerStart.x;
    const dy = e.clientY - pointerStart.y;
    pointerStart = null;
    if (Math.abs(dx) > 40 && Math.abs(dx) > Math.abs(dy) * 1.5) (dx < 0 ? next : prev)();
  });

  /* ---------- Données et flux temps réel ---------- */
  async function fetchJson(url) {
    const res = await fetch(url, { cache: "no-store" });
    if (!res.ok) throw new Error(`${url} → ${res.status}`);
    return res.json();
  }

  async function loadAll() {
    const [topics, articles] = await Promise.all([fetchJson("/api/topics"), fetchJson("/api/articles?limit=60")]);
    state.topics = topics;
    state.articles = articles.articles;
    renderFilters();
    render();
  }

  function insertArticles(list) {
    const known = new Set(state.articles.map((a) => a.id));
    const fresh = list.filter((a) => !known.has(a.id));
    if (!fresh.length) return [];
    const current = visible()[state.index];
    // Les plus récents en tête, dans l'ordre du serveur.
    state.articles = [...fresh, ...state.articles].sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt)));
    for (const a of fresh) state.newIds.add(a.id);
    render({ keepId: current ? current.id : undefined });
    updateStatus({ articleCount: state.articles.length });
    return fresh;
  }

  function showToast(text, onClick) {
    els.toast.textContent = text;
    els.toast.hidden = false;
    els.toast.onclick = () => { els.toast.hidden = true; onClick && onClick(); };
    clearTimeout(showToast.timer);
    showToast.timer = setTimeout(() => { els.toast.hidden = true; }, 8000);
  }

  /* Après une coupure, récupère les articles publiés pendant l'absence du flux. */
  async function resync() {
    try {
      const { articles } = await fetchJson("/api/articles?limit=60");
      const fresh = insertArticles(articles);
      if (fresh.length) showToast(`${T.newArticle} : ${fresh[0].title}`, () => { state.filter = null; renderFilters(); render(); goTo(0); });
    } catch (err) {
      console.warn("resynchronisation impossible", err);
    }
    refreshStatus();
  }

  function connectEvents() {
    if (!("EventSource" in window)) {
      setInterval(resync, 60000);
      return;
    }
    const source = new EventSource("/api/events");
    let opened = false;
    source.addEventListener("open", () => {
      if (!opened) { opened = true; return; } // première ouverture : loadAll() vient de tourner
      resync();
    });
    source.addEventListener("article", (e) => {
      try {
        const article = JSON.parse(e.data);
        const fresh = insertArticles([article]);
        if (fresh.length) showToast(`${T.newArticle} : ${article.title}`, () => { state.filter = null; renderFilters(); render(); goTo(0); });
        refreshStatus();
      } catch (err) {
        console.error("événement article invalide", err);
      }
    });
    source.onerror = () => { /* EventSource se reconnecte seul */ };
  }

  function updateStatus(patch) {
    state.status = Object.assign(state.status || {}, patch);
    const s = state.status;
    els.statusCount.textContent = T.articles(s.articleCount || state.articles.length);
  }

  async function refreshStatus() {
    try {
      const status = await fetchJson("/api/status");
      if (status.now) state.clockOffset = Date.now() - new Date(status.now).getTime();
      updateStatus(status);
      tickCountdown();
    } catch (err) {
      console.warn("statut indisponible", err);
    }
  }

  function tickCountdown() {
    const s = state.status;
    if (!s || !s.scheduler) { els.statusNext.textContent = ""; return; }
    if (s.scheduler.running) { els.statusNext.textContent = `${T.next} ${T.now}`; return; }
    if (!s.scheduler.nextRunAt) { els.statusNext.textContent = ""; return; }
    const serverNow = Date.now() - state.clockOffset;
    const remaining = Math.max(0, new Date(s.scheduler.nextRunAt).getTime() - serverNow);
    const m = Math.floor(remaining / 60000);
    const sec = Math.floor((remaining % 60000) / 1000);
    els.statusNext.textContent = `${T.next} ${m}:${String(sec).padStart(2, "0")}`;
  }

  async function init() {
    await refreshStatus();
    if (state.status && state.status.language) setLang(state.status.language);
    try {
      await loadAll();
    } catch (err) {
      console.error(err);
      els.empty.hidden = false;
      els.empty.textContent = T.loadError;
    }
    connectEvents();
    setPlaying(state.playing);
    requestAnimationFrame(loop);
    setInterval(refreshStatus, 30000);
    setInterval(tickCountdown, 1000);
    tickCountdown();
  }

  init();
})();
