/* Carrousel scientifique — logique côté navigateur (sans dépendance). */
(() => {
  "use strict";

  const AUTOPLAY_MS = 12000;
  const state = {
    articles: [],
    topics: [],
    filter: null,
    index: 0,
    playing: true,
    paused: false,
    timer: null,
    progressStart: 0,
    status: null,
    newIds: new Set(),
  };

  const $ = (id) => document.getElementById(id);
  const els = {
    track: $("track"), viewport: $("viewport"), dots: $("dots"), counter: $("counter"),
    prev: $("prev"), next: $("next"), play: $("play"), progress: $("progress").firstElementChild,
    filters: $("filters"), empty: $("empty"), reader: $("reader"), readerContent: $("reader-content"),
    readerClose: $("reader-close"), toast: $("toast"), statusCount: $("status-count"), statusNext: $("status-next"),
    carousel: $("carousel"),
  };

  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const lang = document.documentElement.lang || "fr";
  const dateFmt = new Intl.DateTimeFormat(lang === "en" ? "en-GB" : "fr-FR", { dateStyle: "medium" });
  const timeFmt = new Intl.DateTimeFormat(lang === "en" ? "en-GB" : "fr-FR", { hour: "2-digit", minute: "2-digit" });
  const T = lang === "en"
    ? { read: "Read the article", source: "Source on PubMed", published: "Published", generated: "Generated", next: "Next article in", now: "generating…", articles: (n) => `${n} article${n > 1 ? "s" : ""}`, newArticle: "New article", keyPoints: "Key points", authors: "Authors", journal: "Journal", pmid: "PMID", doi: "DOI", pubTypes: "Publication types", disclaimer: "Article generated automatically from the PubMed abstract (abstract only, not the full text). It is not medical advice.", generatedBy: "Generated by", image: "Illustration", pause: "Pause autoplay", play: "Resume autoplay", of: "of" }
    : { read: "Lire l'article", source: "Source sur PubMed", published: "Publié le", generated: "Généré le", next: "Prochain article dans", now: "génération en cours…", articles: (n) => `${n} article${n > 1 ? "s" : ""}`, newArticle: "Nouvel article", keyPoints: "Points clés", authors: "Auteurs", journal: "Revue", pmid: "PMID", doi: "DOI", pubTypes: "Types de publication", disclaimer: "Article généré automatiquement à partir du résumé PubMed (résumé seul, pas le texte intégral). Il ne constitue pas un avis médical.", generatedBy: "Généré par", image: "Illustration", pause: "Mettre en pause le défilement automatique", play: "Reprendre le défilement automatique", of: "sur" };

  function formatDate(value) {
    if (!value) return "";
    if (/^\d{4}-\d{2}-\d{2}/.test(value)) {
      const d = new Date(value.length === 10 ? `${value}T12:00:00` : value);
      return Number.isNaN(d.getTime()) ? value : dateFmt.format(d);
    }
    return value;
  }

  function visible() {
    return state.filter ? state.articles.filter((a) => a.topic && a.topic.id === state.filter) : state.articles;
  }

  function hueOf(article) {
    return article.topic && typeof article.topic.hue === "number" ? article.topic.hue : 190;
  }

  /* Les styles en ligne sont interdits par la CSP : la couleur du sujet est posée via CSSOM. */
  function applyHues(root) {
    for (const el of root.querySelectorAll("[data-hue]")) {
      el.style.setProperty("--chip", `hsl(${Number(el.dataset.hue)} 85% 65%)`);
    }
  }

  function slideHtml(article, i) {
    const src = article.source || {};
    const isNew = state.newIds.has(article.id);
    return `
      <li class="slide" data-id="${esc(article.id)}" role="group" aria-roledescription="diapositive" aria-label="${i + 1} ${T.of} ${visible().length}" data-hue="${hueOf(article)}">
        <div class="slide-media">
          ${article.image ? `<img src="${esc(article.image.url)}" alt="${esc(article.image.alt || "")}" ${i === 0 ? "" : 'loading="lazy"'} width="1200" height="675">` : ""}
          <span class="badge">${esc(article.topic ? article.topic.label : "")}</span>
          ${isNew ? `<span class="badge new">${T.newArticle}</span>` : ""}
        </div>
        <div class="slide-body">
          <div class="meta">
            <span class="journal">${esc(src.journal || src.journalAbbrev || "PubMed")}</span>
            ${src.pubDate ? `<span>${T.published} ${esc(formatDate(src.pubDate))}</span>` : ""}
            <span>${T.generated} ${esc(formatDate(article.createdAt))} ${esc(timeFmt.format(new Date(article.createdAt)))}</span>
          </div>
          <h2>${esc(article.title)}</h2>
          <p class="dek">${esc(article.dek)}</p>
          <p class="summary">${esc(article.summary)}</p>
          ${article.keyPoints && article.keyPoints.length ? `<ul class="keypoints">${article.keyPoints.slice(0, 3).map((k) => `<li>${esc(k)}</li>`).join("")}</ul>` : ""}
          <div class="tags">${(article.tags || []).slice(0, 6).map((t) => `<span class="tag">${esc(t)}</span>`).join("")}</div>
          <div class="actions">
            <button class="btn" type="button" data-read="${esc(article.id)}">${T.read}</button>
            ${src.url ? `<a class="link" href="${esc(src.url)}" target="_blank" rel="noopener noreferrer">${T.source} ↗</a>` : ""}
          </div>
        </div>
      </li>`;
  }

  function render({ keepId } = {}) {
    const list = visible();
    els.empty.hidden = list.length > 0;
    els.carousel.style.visibility = list.length ? "visible" : "hidden";
    els.track.innerHTML = list.map(slideHtml).join("");
    applyHues(els.track);
    els.dots.innerHTML = list.map((a, i) => `<li><button type="button" data-goto="${i}" aria-label="Article ${i + 1}: ${esc(a.title)}"></button></li>`).join("");
    if (keepId) {
      const idx = list.findIndex((a) => a.id === keepId);
      state.index = idx >= 0 ? idx : 0;
    }
    state.index = Math.min(state.index, Math.max(list.length - 1, 0));
    position({ animate: false });
  }

  function position({ animate = true } = {}) {
    const list = visible();
    els.track.classList.toggle("no-anim", !animate);
    els.track.style.transform = `translateX(-${state.index * 100}%)`;
    if (!animate) void els.track.offsetWidth; // force le reflow pour que la prochaine transition s'anime
    els.counter.textContent = list.length ? `${state.index + 1} / ${list.length}` : "";
    for (const btn of els.dots.querySelectorAll("button")) {
      btn.setAttribute("aria-current", Number(btn.dataset.goto) === state.index ? "true" : "false");
    }
    els.prev.disabled = list.length < 2;
    els.next.disabled = list.length < 2;
    restartProgress();
  }

  function goTo(i, opts) {
    const n = visible().length;
    if (!n) return;
    state.index = ((i % n) + n) % n;
    position(opts);
  }
  const next = () => goTo(state.index + 1);
  const prev = () => goTo(state.index - 1);

  /* Défilement automatique avec barre de progression */
  function restartProgress() {
    state.progressStart = performance.now();
    els.progress.style.width = "0%";
  }
  function loop(now) {
    if (state.playing && !state.paused && visible().length > 1) {
      const elapsed = now - state.progressStart;
      els.progress.style.width = `${Math.min(100, (elapsed / AUTOPLAY_MS) * 100)}%`;
      if (elapsed >= AUTOPLAY_MS) next();
    } else {
      state.progressStart = now - (parseFloat(els.progress.style.width) || 0) / 100 * AUTOPLAY_MS;
    }
    requestAnimationFrame(loop);
  }
  function setPlaying(playing) {
    state.playing = playing;
    els.play.setAttribute("aria-pressed", String(playing));
    els.play.textContent = playing ? "❚❚" : "▶";
    els.play.setAttribute("aria-label", playing ? T.pause : T.play);
    if (playing) restartProgress();
  }

  /* Lecteur d'article complet */
  function openReader(article) {
    const src = article.source || {};
    const authors = (src.authors || []).slice(0, 10).join(", ") + ((src.authors || []).length > 10 ? " et al." : "");
    els.readerContent.innerHTML = `
      <span class="badge badge-inline" data-hue="${hueOf(article)}">${esc(article.topic ? article.topic.label : "")}</span>
      <h2 id="reader-title">${esc(article.title)}</h2>
      <p class="dek">${esc(article.dek)}</p>
      ${article.image ? `<img src="${esc(article.image.url)}" alt="${esc(article.image.alt || "")}" width="1200" height="675">` : ""}
      <p><strong>${esc(article.summary)}</strong></p>
      ${(article.sections || []).map((s) => `<h3>${esc(s.heading)}</h3><p>${esc(s.content)}</p>`).join("")}
      ${article.keyPoints && article.keyPoints.length ? `<h3>${T.keyPoints}</h3><ul>${article.keyPoints.map((k) => `<li>${esc(k)}</li>`).join("")}</ul>` : ""}
      <div class="tags">${(article.tags || []).map((t) => `<span class="tag">${esc(t)}</span>`).join("")}</div>
      <div class="source">
        <div><strong>${esc(src.title || "")}</strong></div>
        ${authors ? `<div>${T.authors} : ${esc(authors)}</div>` : ""}
        <div>${T.journal} : ${esc(src.journal || "")}${src.pubDate ? ` · ${T.published} ${esc(formatDate(src.pubDate))}` : ""}</div>
        ${src.publicationTypes && src.publicationTypes.length ? `<div>${T.pubTypes} : ${esc(src.publicationTypes.join(", "))}</div>` : ""}
        <div>${T.pmid} : <a href="${esc(src.url)}" target="_blank" rel="noopener noreferrer">${esc(src.pmid)}</a>${src.doi ? ` · ${T.doi} : <a href="${esc(src.doiUrl || `https://doi.org/${src.doi}`)}" target="_blank" rel="noopener noreferrer">${esc(src.doi)}</a>` : ""}</div>
        <p class="disclaimer">${T.disclaimer} ${T.generatedBy} ${esc(article.generator || "")} · ${T.image} : ${esc(article.image ? article.image.provider : "")}.</p>
      </div>`;
    applyHues(els.readerContent);
    state.paused = true;
    els.reader.showModal();
    els.readerContent.scrollTop = 0;
  }
  els.readerClose.addEventListener("click", () => els.reader.close());
  els.reader.addEventListener("close", () => { state.paused = false; restartProgress(); });
  els.reader.addEventListener("click", (e) => { if (e.target === els.reader) els.reader.close(); });

  /* Filtres par sujet */
  function renderFilters() {
    const all = `<button type="button" data-topic="" aria-pressed="${state.filter ? "false" : "true"}">${lang === "en" ? "All" : "Tous"}</button>`;
    els.filters.innerHTML = all + state.topics.map((t) =>
      `<button type="button" data-topic="${esc(t.id)}" aria-pressed="${state.filter === t.id ? "true" : "false"}" data-hue="${Number(t.hue) || 190}">${esc(t.label)}</button>`).join("");
    applyHues(els.filters);
  }
  els.filters.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-topic]");
    if (!btn) return;
    state.filter = btn.dataset.topic || null;
    state.index = 0;
    renderFilters();
    render();
  });

  /* Événements de navigation */
  els.next.addEventListener("click", next);
  els.prev.addEventListener("click", prev);
  els.play.addEventListener("click", () => setPlaying(!state.playing));
  els.dots.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-goto]");
    if (btn) goTo(Number(btn.dataset.goto));
  });
  els.track.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-read]");
    if (!btn) return;
    const article = state.articles.find((a) => a.id === btn.dataset.read);
    if (article) openReader(article);
  });
  document.addEventListener("keydown", (e) => {
    if (els.reader.open) return;
    if (e.key === "ArrowRight") next();
    else if (e.key === "ArrowLeft") prev();
    else if (e.key === " " && e.target === document.body) { e.preventDefault(); setPlaying(!state.playing); }
  });
  els.carousel.addEventListener("mouseenter", () => { state.paused = true; });
  els.carousel.addEventListener("mouseleave", () => { if (!els.reader.open) state.paused = false; });
  els.carousel.addEventListener("focusin", () => { state.paused = true; });
  els.carousel.addEventListener("focusout", () => { if (!els.reader.open) state.paused = false; });
  document.addEventListener("visibilitychange", () => { state.paused = document.hidden || els.reader.open; });

  let pointerStart = null;
  els.viewport.addEventListener("pointerdown", (e) => { pointerStart = { x: e.clientX, y: e.clientY, t: Date.now() }; });
  els.viewport.addEventListener("pointerup", (e) => {
    if (!pointerStart) return;
    const dx = e.clientX - pointerStart.x;
    const dy = e.clientY - pointerStart.y;
    pointerStart = null;
    if (Math.abs(dx) > 40 && Math.abs(dx) > Math.abs(dy) * 1.5) (dx < 0 ? next : prev)();
  });

  /* Chargement des données et flux temps réel */
  async function fetchJson(url) {
    const res = await fetch(url, { cache: "no-store" });
    if (!res.ok) throw new Error(`${url} → ${res.status}`);
    return res.json();
  }

  async function loadAll() {
    const [topics, articles] = await Promise.all([fetchJson("/api/topics"), fetchJson("/api/articles?limit=60")]);
    state.topics = topics;
    state.articles = articles.articles;
    renderFilters();
    render();
  }

  function showToast(text, onClick) {
    els.toast.textContent = text;
    els.toast.hidden = false;
    els.toast.onclick = () => { els.toast.hidden = true; onClick && onClick(); };
    clearTimeout(showToast.timer);
    showToast.timer = setTimeout(() => { els.toast.hidden = true; }, 8000);
  }

  function connectEvents() {
    if (!("EventSource" in window)) return;
    const source = new EventSource("/api/events");
    source.addEventListener("article", (e) => {
      try {
        const article = JSON.parse(e.data);
        if (state.articles.some((a) => a.id === article.id)) return;
        const current = visible()[state.index];
        state.articles.unshift(article);
        state.newIds.add(article.id);
        render({ keepId: current ? current.id : undefined });
        updateStatus({ articleCount: state.articles.length });
        showToast(`${T.newArticle} : ${article.title}`, () => { state.filter = null; renderFilters(); render(); goTo(0, { animate: true }); });
      } catch (err) {
        console.error("événement article invalide", err);
      }
    });
    source.onerror = () => { /* EventSource se reconnecte seul */ };
  }

  function updateStatus(patch) {
    state.status = Object.assign(state.status || {}, patch);
    const s = state.status;
    els.statusCount.textContent = T.articles(s.articleCount || state.articles.length);
  }

  async function refreshStatus() {
    try {
      const status = await fetchJson("/api/status");
      updateStatus(status);
    } catch (err) {
      console.warn("statut indisponible", err);
    }
  }

  function tickCountdown() {
    const s = state.status;
    if (!s || !s.scheduler) { els.statusNext.textContent = ""; return; }
    if (s.scheduler.running) { els.statusNext.textContent = `${T.next} ${T.now}`; return; }
    if (!s.scheduler.nextRunAt) { els.statusNext.textContent = ""; return; }
    const remaining = Math.max(0, new Date(s.scheduler.nextRunAt).getTime() - (Date.now() - state.clockOffset));
    const m = Math.floor(remaining / 60000);
    const sec = Math.floor((remaining % 60000) / 1000);
    els.statusNext.textContent = `${T.next} ${m}:${String(sec).padStart(2, "0")}`;
  }

  async function init() {
    state.clockOffset = 0;
    try {
      await loadAll();
    } catch (err) {
      console.error(err);
      els.empty.hidden = false;
      els.empty.textContent = lang === "en" ? "Unable to load articles." : "Impossible de charger les articles.";
    }
    await refreshStatus();
    if (state.status && state.status.now) state.clockOffset = Date.now() - new Date(state.status.now).getTime();
    connectEvents();
    setPlaying(true);
    requestAnimationFrame(loop);
    setInterval(refreshStatus, 30000);
    setInterval(tickCountdown, 1000);
    tickCountdown();
  }

  init();
})();
